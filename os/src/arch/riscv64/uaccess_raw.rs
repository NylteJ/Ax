    #[unsafe(naked)]
    #[unsafe(link_section = ".text.uaccess.strcpy")]
    #[unsafe(no_mangle)]
    unsafe extern "C" fn __strcpy_uaccess(
        u_src: *const u8,
        k_buf: *mut u8,
        buf_length: usize,
    ) -> usize {
        #[rustfmt::skip]
        naked_asm!(
            "mv      a3, a0",
        ".LBB0_1:",
            "lbu     a5, 0(a3)",
            "beqz    a5, .LBB0_4",
            "sb      a5, 0(a1)",
            "addi    a3, a3, 1",
            "addi    a2, a2, -1",
            "addi    a1, a1, 1",
            "bnez    a2, .LBB0_1",
        ".LBB0_4:",
            "sub     a0, a3, a0",
            "ret",
        ".globl  __strcpy_uaccess_fault",
        "__strcpy_uaccess_fault:",
            "li      a0, {FAULT_RET}",
            "ret",
            FAULT_RET = const usize::MAX,
        );
    }

