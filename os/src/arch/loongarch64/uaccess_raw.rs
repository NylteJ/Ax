    #[unsafe(naked)]
    #[unsafe(link_section = ".text.uaccess.strcpy")]
    #[unsafe(no_mangle)]
    unsafe extern "C" fn __strcpy_uaccess(
        u_src: *const u8,
        k_buf: *mut u8,
        buf_length: usize,
    ) -> usize {
        #[rustfmt::skip]
        naked_asm!(
            "move    $a3, $a0",
            "move    $a0, $zero",
        ".LBB1_1:",
            "ldx.bu  $a4, $a3, $a0",
            "beqz    $a4, .LBB1_4",
            "stx.b   $a4, $a1, $a0",
            "addi.d  $a0, $a0, 1",
            "bne     $a2, $a0, .LBB1_1",
            "move    $a0, $a2",
        ".LBB1_4:",
            "ret",
        ".globl  __strcpy_uaccess_fault",
        "__strcpy_uaccess_fault:",
            "li.d    $a0, {FAULT_RET}",
            "ret",
            FAULT_RET = const usize::MAX,
        );
    }

